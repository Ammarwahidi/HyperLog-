export function resolveExerciseModality(
  ex: Pick<LibraryExercise, 'modality' | 'equipment' | 'name'>
): Exclude<ExerciseModality, ExerciseModality.All> {
  if (ex.modality) return ex.modality;
  if (ex.equipment === EquipmentType.CardioMachine) return ExerciseModality.Cardio;
  if (ex.equipment === EquipmentType.Mat) return ExerciseModality.Yoga;
  return ExerciseModality.Strength;
}

export function resolveTemplateModality(
  tpl: Pick<WorkoutTemplate, 'modality' | 'splitType' | 'name'>
): Exclude<ExerciseModality, ExerciseModality.All> {
  if (tpl.modality) return tpl.modality;
  const text = `${tpl.splitType} ${tpl.name}`.toLowerCase();
  if (text.includes('yoga') || text.includes('vinyasa') || text.includes('yin')) {
    return ExerciseModality.Yoga;
  }
  if (text.includes('stretch') || text.includes('mobility') || text.includes('prehab')) {
    return ExerciseModality.Stretching;
  }
  if (text.includes('cardio') || text.includes('hiit') || text.includes('zone 2') || text.includes('conditioning')) {
    return ExerciseModality.Cardio;
  }
  return ExerciseModality.Strength;
}

