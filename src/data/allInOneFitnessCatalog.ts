export function groupExercisesByMuscleSection(
  exercises: LibraryExercise[]
): ExerciseGroupSection[] {
  const buckets = new Map<string, ExerciseGroupSection>();

  for (const ex of exercises) {
    const mod = resolveExerciseModality(ex);
    if (mod === ExerciseModality.Yoga) {
      const key = 'mod_yoga';
      if (!buckets.has(key)) {
        buckets.set(key, {
          key,
          title: 'Yoga Poses & Flows',
          subtitle: 'Breath-synchronized postures, balance, hip openers & restorative holds',
          items: [],
        });
      }
      buckets.get(key)!.items.push(ex);
      continue;
    }

    if (mod === ExerciseModality.Stretching) {
      const key = 'mod_stretching';
      if (!buckets.has(key)) {
        buckets.set(key, {
          key,
          title: 'Stretching & Mobility',
          subtitle: 'Joint range of motion, myofascial release & active flexibility',
          items: [],
        });
      }
      buckets.get(key)!.items.push(ex);
      continue;
    }

    if (mod === ExerciseModality.Cardio) {
      const key = 'mod_cardio';
      if (!buckets.has(key)) {
        buckets.set(key, {
          key,
          title: 'Cardio & Conditioning',
          subtitle: 'Zone 2 aerobic endurance, ergometers, plyometrics & HIIT intervals',
          items: [],
        });
      }
      buckets.get(key)!.items.push(ex);
      continue;
    }

    const meta = GROUP_SECTION_META[ex.majorGroup] ?? GROUP_SECTION_META[MajorMuscleGroup.Legs];
    const key = `mg_${ex.majorGroup}`;
    if (!buckets.has(key)) {
      buckets.set(key, {
        key,
        title: meta.title,
        subtitle: meta.subtitle,
        items: [],
      });
    }
    buckets.get(key)!.items.push(ex);
  }

  const orderRank = (k: string): number => {
    if (k === `mg_${MajorMuscleGroup.Chest}`) return 1;
    if (k === `mg_${MajorMuscleGroup.Back}`) return 2;
    if (k === `mg_${MajorMuscleGroup.Shoulders}`) return 3;
    if (k === `mg_${MajorMuscleGroup.Arms}`) return 4;
    if (k === `mg_${MajorMuscleGroup.Core}`) return 5;
    if (k === `mg_${MajorMuscleGroup.Legs}`) return 6;
    if (k === 'mod_cardio') return 7;
    if (k === 'mod_yoga') return 8;
    if (k === 'mod_stretching') return 9;
    return 99;
  };

  return Array.from(buckets.values())
    .sort((a, b) => orderRank(a.key) - orderRank(b.key))
    .map((sec) => ({
      ...sec,
      items: [...sec.items].sort((a, b) => a.name.localeCompare(b.name)),
    }));
}

