export function evaluateVolumeZone(sets: number, landmark: MuscleLandmark): VolumeZone {
  if (sets >= landmark.mrv) {
    return VolumeZone.Overreaching;
  }
  if (sets >= landmark.mavMin) {
    return VolumeZone.OptimalMAV;
  }
  if (sets > landmark.mev && sets < landmark.mavMin) {
    return VolumeZone.Productive;
  }
  if (sets >= landmark.mv && sets <= landmark.mev && sets > 0) {
    return VolumeZone.Maintenance;
  }
  if (landmark.mev === 0 && sets > 0) {
    return VolumeZone.Productive;
  }
  return VolumeZone.BelowMV;
}

